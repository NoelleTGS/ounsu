#!/usr/bin/env python3
"""Generate the static OpenSSL symbol table for hbxl_vk_shim.c's fake dlsym.

.NET's OpenSSL shim (System.Security.Cryptography.Native.OpenSsl) dlopen()s libssl and
dlsym()s each function by name.  hbxl has no dynamic loader, so this lists every global
function/data symbol defined in libssl.a + libcrypto.a, sorted for binary search.
Referencing them all pulls the whole of OpenSSL into the link, which is intended.

usage: gen-ssl-syms.py [--table NAME] <nm> <out.c> lib.a...
  --table ffmpeg emits hbxl_ffmpeg_syms/hbxl_ffmpeg_count (default: ssl) for static FFmpeg.
"""
import subprocess
import sys
from pathlib import Path

args = sys.argv[1:]
table = "ssl"
if args[0] == "--table":
    table, args = args[1], args[2:]
nm, out, libs = args[0], Path(args[1]), args[2:]
names = set()
for lib in libs:
    for line in subprocess.run([nm, "--defined-only", "-g", lib], capture_output=True, text=True, check=True).stdout.splitlines():
        parts = line.split()
        if len(parts) == 3 and parts[1] in "TDRB" and parts[2].isidentifier():
            names.add(parts[2])
names = sorted(names)  # Python's default sort is strcmp order for ASCII identifiers
c = ["/* Generated by gen-ssl-syms.py: do not edit. */",
     "struct hbxl_dl_sym { const char *name; void *addr; };"]
c += [f"extern char {n}[];" for n in names]
c += [f"const unsigned hbxl_{table}_count = {len(names)};",
      f"const struct hbxl_dl_sym hbxl_{table}_syms[] = {{"]
c += [f'    {{"{n}", {n}}},' for n in names]
c += ["};", ""]
out.write_text("\n".join(c))
print(f"gen-ssl-syms ({table}): {len(names)} symbols -> {out}")
