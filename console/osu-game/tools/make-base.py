#!/usr/bin/env python3
"""Per-app manifest fields for osu-game (cut-down osu!), including the static native libraries."""
import json
import sys
from pathlib import Path

root = Path(sys.argv[1])
native = root / "src/native"
spirv = native / "veldrid-spirv/build-hbx"
# veldrid-spirv + shaderc + glslang + SPIRV-Tools + SPIRV-Cross: every static library the
# build produced (link order is handled with --start-group/--end-group).
spirv_libs = sorted(str(p) for p in spirv.rglob("*.a")) if spirv.is_dir() else []
# osu! database libraries: SQLite (amalgamation 3.50.4) and Realm (realm-dotnet 20.1.0
# wrappers + realm-core, static, no sync/encryption, generic commit helper).
sqlite_libs = [str(native / "sqlite-dl/build-hbx/libe_sqlite3.a")]
realm_dir = native / "realm-dotnet/wrappers/build-hbx"
realm_libs = sorted(str(p) for p in realm_dir.rglob("*.a")) if realm_dir.is_dir() else []
if not realm_libs:
    print("make-base: WARNING: no static Realm build yet (src/native/realm-dotnet/wrappers/build-hbx)", file=sys.stderr)

# Static OpenSSL for .NET crypto (MD5/SHA for shader cache keys, beatmap hashes, HTTPS):
# hbxl_vk_shim.c's dlopen("libssl.so.3") resolves through obj/ssl_syms.c.
openssl = native / "openssl"
ssl_libs = [str(openssl / "libssl.a"), str(openssl / "libcrypto.a")]
have_ssl = all(Path(l).is_file() for l in ssl_libs)
if not have_ssl:
    print("make-base: WARNING: no static OpenSSL; .NET crypto (MD5/SHA) will abort", file=sys.stderr)
# Static FFmpeg 7.1.1 (tools/build-ffmpeg-hbx.sh) for audio decoding (mysoundlib):
# hbxl_vk_shim.c's dlopen("libavcodec.so.61") resolves through obj/ffmpeg_syms.c.
ffmpeg = native / "ffmpeg/build-hbx/lib"
ffmpeg_libs = [str(ffmpeg / f"lib{n}.a") for n in ("avformat", "avcodec", "swresample", "avutil")]
have_ffmpeg = all(Path(l).is_file() for l in ffmpeg_libs)
if not have_ffmpeg:
    print("make-base: WARNING: no static FFmpeg; audio can't decode (run tools/build-ffmpeg-hbx.sh)", file=sys.stderr)
print(json.dumps({
    "id": "osu-game",
    "name": "osu!",
    "description": "osu! (lazer), console build",
    "icon": "icon.png",  # generated by tools/make-icon.py (build.sh) from the extracted osu! resources
    "display": "exclusive",
    # veldrid-spirv is real C++ and links -lstdc++: drop NativeAOT's libstdc++ stand-in.
    "exclude_objects": ["libstdc++compat.a"],
    "sources": ["../shim/hbxl_vk_shim.c", "../obj/vk/vk_tramp.S", "../obj/vk/vk_names.c",
                "../shim/bass_stubs.S", "../shim/bass_devices.c", "../shim/hbxl_thread_stacks.c",
                "../shim/hbxl_input.c", "../shim/hbxl_audio_out.c",
                "../shim/hbxl_gc_timing.c", "../shim/hbxl_net.c",
                "../../../probes/gfx-probe/shim/hbxl_thunks.S", "../../../probes/gfx-probe/shim/hbxl_thunks.c"]
               + (["../obj/ssl_syms.c"] if have_ssl else [])
               + (["../obj/ffmpeg_syms.c"] if have_ffmpeg else []),
    "linux": {
        "code_base": "0x20000000",
        "data_base": "after_code",   # NativeAOT delegate thunks (hbxl_thunks.S), Realm callbacks
        "objects": [str(native / "SDL/build-hbx/libSDL3.a")],
        # hbxl_input.c (touchscreen/controller → SDL events) uses SDL's public headers only.
        "cflags": [f"-I{native / 'SDL/include'}"],
        # hbxl_net.c: names resolve through the console's resolver (sdk/linux/net.c), not musl's.
        "ldflags": ["-Wl,--wrap=getaddrinfo", "-Wl,--wrap=freeaddrinfo", "-Wl,--wrap=pthread_create", "-Wl,--wrap=RhAllocateThunksMapping", "-Wl,--wrap=SDL_PumpEvents",
                    # hbxl_audio_out.c: own AudioOut queue (HBXL_AUDIO_PERIOD/BUFFERS) instead of SDL hbx driver's fixed 85 ms.
                    "-Wl,--wrap=SDL_OpenAudioDeviceStream", "-Wl,--wrap=SDL_ResumeAudioStreamDevice", "-Wl,--wrap=SDL_PauseAudioStreamDevice", "-Wl,--wrap=SDL_DestroyAudioStream",
                    # GC thread activation emulation (hbxl_dotnet_shim.c): no signals on hbxl.
                    "-Wl,--wrap=_Z9PalHijackP6Thread", "-Wl,--wrap=_ZN11ThreadStore17SuspendAllThreadsEb", "-Wl,--wrap=_ZN11ThreadStore16ResumeAllThreadsEb", "-Wl,--wrap=minipal_microdelay", "-Wl,--wrap=_Z17PalSwitchToThreadv", "-Wl,--wrap=RhpCollect", "-Wl,--start-group", *spirv_libs, *(ssl_libs if have_ssl else []), *sqlite_libs, *realm_libs, *(ffmpeg_libs if have_ffmpeg else []), "-Wl,--end-group"],
        "libs": ["-lstdc++"],
    },
    "limits": {"heap_bytes": 65536, "stack_bytes": 1572864, "frames": 0},
}, indent=2))
