#!/usr/bin/env python3
"""Generate shim/bass_stubs.S: BASS functions osu-framework references, stubbed to fail.

BASS is closed source with no build for the console, so for now every call reports
failure: x0 = 0 and d0 = 0.0 (covers integer, pointer, bool, float and double returns).
osu-framework then logs "BASS failed to initialize" and runs without audio.
The real audio backend will be osu-framework PR #6002 (SDL3 + mysoundlib).

usage: gen-bass-stubs.py undefined.txt shim/bass_stubs.S
  undefined.txt: one undefined BASS_* symbol per line, from a failed hbxl-build link.
"""
import sys
from pathlib import Path

SPECIAL = {
    "BASS_ErrorGetCode": 23,          # BASS_ERROR_DEVICE: "illegal device number"
    "BASS_GetVersion": 0x02041100,    # 2.4.17.0
    "BASS_FX_GetVersion": 0x02041100,
    "BASS_Mixer_GetVersion": 0x02041100,
}
# Implemented in C instead (shim/bass_devices.c).
IN_C = {"BASS_GetDeviceInfo"}
names = sorted({l.strip() for l in Path(sys.argv[1]).read_text().splitlines()
                if l.strip().startswith("BASS")} - IN_C)
out = ["/* Generated by tools/gen-bass-stubs.py: do not edit. */", "    .text"]
for n in names:
    v = SPECIAL.get(n, 0)
    out += ["    .p2align 2", f"    .global {n}", f"    .type {n}, %function", f"{n}:", "    bti c"]
    if v > 0xffff:
        out += [f"    mov w0, #{v & 0xffff}", f"    movk w0, #{v >> 16}, lsl #16"]
    else:
        out += [f"    mov x0, #{v}"]
    out += ["    movi d0, #0", "    ret", f"    .size {n}, . - {n}"]
out += ['    .section .note.GNU-stack,"",%progbits', ""]
Path(sys.argv[2]).write_text("\n".join(out))
print(f"gen-bass-stubs: {len(names)} stubs -> {sys.argv[2]}")
