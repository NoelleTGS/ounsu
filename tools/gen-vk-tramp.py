#!/usr/bin/env python3
"""Generate lazy-resolving Vulkan trampolines for lx/dotnet/lx_vk.c.

ppy.Vk (vk.dll) dlsym()s every Vulkan command once, before any VkInstance
exists.  The console only resolves most commands through
vk_icdGetInstanceProcAddr(instance, name) or vkGetDeviceProcAddr(device, name),
so dlsym hands out one trampoline per command instead.  On its first call
the trampoline asks lx_vk_resolve(index) for the real pointer, caches it in
lx_vk_slots[index], and tail-calls it with the original arguments intact.

Every trampoline is exactly 8 instructions (32 bytes), so trampoline i lives
at lx_vk_tramps + 32 * i.

usage: gen-vk-tramp.py vulkan_core.h out_dir
"""
import re
import sys
from pathlib import Path

header, out = Path(sys.argv[1]), Path(sys.argv[2])
# name -> first parameter type, e.g. "VkDevice" (device-level) or "VkPhysicalDevice"
first = dict(re.findall(r"\(VKAPI_PTR \*PFN_(vk\w+)\)\(\s*(?:const\s+)?(\w+)", header.read_text()))
names = sorted(first)
# Device-level commands dispatch on a VkDevice/VkQueue/VkCommandBuffer.  Only these may
# be resolved through vkGetDeviceProcAddr: the console's driver returns non-NULL (and
# wrong) pointers there for instance-level commands too.
device_level = {n for n, t in first.items()
                if t in ("VkDevice", "VkQueue", "VkCommandBuffer") and n != "vkGetDeviceProcAddr"}
assert 0 < len(names) < 4096, len(names)  # ldr's scaled 12-bit offset reaches 4095 slots
out.mkdir(parents=True, exist_ok=True)

asm = [
    "/* Generated by gen-vk-tramp.py: do not edit. */",
    "    .text",
    "    .p2align 5",
    "    .global lx_vk_tramps",
    "lx_vk_tramps:",
]
for i, name in enumerate(names):
    asm += [
        f"    /* {i}: {name} */",
        "    bti c",
        "    adrp x16, lx_vk_slots",
        "    add x16, x16, :lo12:lx_vk_slots",
        f"    ldr x17, [x16, #{8 * i}]",
        f"    cbz x17, 1f",
        "    br x17",
        f"1:  mov x17, #{i}",
        "    b lx_vk_tramp_slow",
    ]
asm += [
    "",
    "/* Save every argument register (x0-x8, d0-d7), resolve, restore, jump. */",
    "    .p2align 2",
    "lx_vk_tramp_slow:",
    "    stp x29, x30, [sp, #-160]!",
    "    mov x29, sp",
    "    stp x0, x1, [sp, #16]",
    "    stp x2, x3, [sp, #32]",
    "    stp x4, x5, [sp, #48]",
    "    stp x6, x7, [sp, #64]",
    "    str x8, [sp, #80]",
    "    stp d0, d1, [sp, #96]",
    "    stp d2, d3, [sp, #112]",
    "    stp d4, d5, [sp, #128]",
    "    stp d6, d7, [sp, #144]",
    "    mov w0, w17",
    "    bl lx_vk_resolve",
    "    mov x16, x0",
    "    ldp d6, d7, [sp, #144]",
    "    ldp d4, d5, [sp, #128]",
    "    ldp d2, d3, [sp, #112]",
    "    ldp d0, d1, [sp, #96]",
    "    ldr x8, [sp, #80]",
    "    ldp x6, x7, [sp, #64]",
    "    ldp x4, x5, [sp, #48]",
    "    ldp x2, x3, [sp, #32]",
    "    ldp x0, x1, [sp, #16]",
    "    ldp x29, x30, [sp], #160",
    "    br x16",
    "",
    '    .section .note.GNU-stack,"",%progbits',
    "",
]
(out / "vk_tramp.S").write_text("\n".join(asm))

c = ["/* Generated by gen-vk-tramp.py: do not edit. */",
     f"const unsigned lx_vk_count = {len(names)};",
     f"void *lx_vk_slots[{len(names)}];",
     "const char *const lx_vk_names[] = {"]
c += [f'    "{n}",' for n in names]
c += ["};", "const unsigned char lx_vk_device_level[] = {"]
c += [f"    {1 if n in device_level else 0}, /* {n} */" for n in names]
c += ["};", ""]
(out / "vk_names.c").write_text("\n".join(c))
print(f"gen-vk-tramp: {len(names)} commands ({len(device_level)} device-level) -> {out}")
