using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Reflection;
using System.Runtime.Loader;
using System.Text;

// Newtonsoft.Json creates collection instances (List<T>, Dictionary<K,V>) by reflection while deserializing API
// responses.  NativeAOT only has code for generic instantiations it saw at compile time, and value-type instantiations
// can't share canonical code, so e.g. List<BeatmapSetOnlineNomination> failed with "missing native code or metadata".
// This lists every collection-shaped member type over value types in osu!'s assemblies and keeps them via rd.xml.
string dir = Path.GetFullPath(args[0]);
string output = args[1];
var alc = new AssemblyLoadContext("scan", isCollectible: false);
alc.Resolving += (ctx, name) =>
{
    string p = Path.Combine(dir, name.Name + ".dll");
    return File.Exists(p) ? ctx.LoadFromAssemblyPath(p) : null;
};

var listLike = new HashSet<string>
{
    "System.Collections.Generic.IEnumerable`1", "System.Collections.Generic.ICollection`1", "System.Collections.Generic.IList`1",
    "System.Collections.Generic.IReadOnlyCollection`1", "System.Collections.Generic.IReadOnlyList`1", "System.Collections.Generic.List`1",
    "System.Collections.Generic.ISet`1", "System.Collections.Generic.HashSet`1",
};
var dictLike = new HashSet<string>
{
    "System.Collections.Generic.IDictionary`2", "System.Collections.Generic.IReadOnlyDictionary`2", "System.Collections.Generic.Dictionary`2",
};

var keep = new SortedSet<string>(StringComparer.Ordinal);
var seen = new HashSet<Type>();

string Arg(Type t) => $"[{Name(t)},{t.Assembly.GetName().Name}]";
string Name(Type t) => t.IsGenericType
    ? t.GetGenericTypeDefinition().FullName + "[" + string.Join(",", t.GetGenericArguments().Select(Arg)) + "]"
    : t.FullName!;

bool Usable(Type t) => t.IsValueType && !t.IsByRefLike && !t.ContainsGenericParameters && !t.IsPointer && t.FullName != null
                       && !t.IsGenericTypeDefinition;

void Add(string def, params Type[] args)
{
    string asm = "System.Private.CoreLib";
    keep.Add($"{asm}|{def}[{string.Join(",", args.Select(Arg))}]");
}

void Walk(Type? t)
{
    if (t == null || t.IsGenericParameter || !seen.Add(t)) return;
    if (t.IsByRef || t.IsPointer) { Walk(t.GetElementType()); return; }
    if (t.IsArray)
    {
        var e = t.GetElementType()!;
        if (Usable(e)) Add("System.Collections.Generic.List`1", e);
        Walk(e);
        return;
    }
    if (!t.IsGenericType || t.ContainsGenericParameters) return;
    var a = t.GetGenericArguments();
    foreach (var x in a) Walk(x);
    string def = t.GetGenericTypeDefinition().FullName!;
    if (listLike.Contains(def) && Usable(a[0])) Add("System.Collections.Generic.List`1", a[0]);
    if (dictLike.Contains(def) && (Usable(a[0]) || Usable(a[1])) && !a.Any(x => x.ContainsGenericParameters || x.IsByRefLike))
        Add("System.Collections.Generic.Dictionary`2", a[0], a[1]);
}

const BindingFlags all = BindingFlags.Instance | BindingFlags.Public | BindingFlags.NonPublic | BindingFlags.DeclaredOnly;
int types = 0;
foreach (string file in Directory.GetFiles(dir, "osu.Game*.dll"))
{
    Assembly asm;
    try { asm = alc.LoadFromAssemblyPath(file); } catch { continue; }
    Type?[] ts;
    try { ts = asm.GetTypes(); } catch (ReflectionTypeLoadException e) { ts = e.Types; }
    foreach (var t in ts)
    {
        if (t == null || t.ContainsGenericParameters) continue;
        types++;
        try
        {
            foreach (var p in t.GetProperties(all)) { try { Walk(p.PropertyType); } catch { } }
            foreach (var f in t.GetFields(all)) { try { Walk(f.FieldType); } catch { } }
        }
        catch { }
    }
}

var sb = new StringBuilder();
sb.AppendLine("<!-- Generated by tools/gen-rdxml (do not edit): collection instantiations Newtonsoft.Json creates by reflection,");
sb.AppendLine("     which NativeAOT otherwise has no code for.  Plus the Cursor extension-data dictionary (osu.Game Online/API/Requests/Cursor.cs). -->");
sb.AppendLine("<Directives xmlns=\"http://schemas.microsoft.com/netfx/2013/01/metadata\">");
sb.AppendLine("  <Application>");
sb.AppendLine("    <Assembly Name=\"System.Private.CoreLib\">");
foreach (var k in keep) sb.AppendLine($"      <Type Name=\"{System.Security.SecurityElement.Escape(k.Split('|')[1])}\" Dynamic=\"Required All\" />");
sb.AppendLine("      <Type Name=\"System.Collections.Generic.IDictionary`2[[System.String,System.Private.CoreLib],[Newtonsoft.Json.Linq.JToken,Newtonsoft.Json]]\" Dynamic=\"Required All\" />");
sb.AppendLine("      <Type Name=\"System.Collections.Generic.Dictionary`2[[System.String,System.Private.CoreLib],[Newtonsoft.Json.Linq.JToken,Newtonsoft.Json]]\" Dynamic=\"Required All\" />");
sb.AppendLine("      <Type Name=\"System.Collections.Generic.ICollection`1[[System.Collections.Generic.KeyValuePair`2[[System.String,System.Private.CoreLib],[Newtonsoft.Json.Linq.JToken,Newtonsoft.Json]],System.Private.CoreLib]]\" Dynamic=\"Required All\" />");
sb.AppendLine("    </Assembly>");
sb.AppendLine("  </Application>");
sb.AppendLine("</Directives>");
File.WriteAllText(output, sb.ToString());
Console.WriteLine($"gen-rdxml: {types} types scanned, {keep.Count} instantiations -> {output}");
